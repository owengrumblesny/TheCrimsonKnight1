"""Cut Owen's concept/asset sheets into individual named images.

Reads config/board_slices.json, crops every labelled panel from the full-resolution boards in
references/original_images, and writes:
  assets/images/<category>/<board>_<label>.png       one image per panel (native resolution)
  assets/images/<category>/<board>_<label>_fNN.png   individual frames for animation strips
  config/image_catalog.json                          id -> file, category, board, rect, frames
  references/renders/board_overlays/<board>.jpg      crop boxes drawn on each board (for checking)

Usage (project root):  python tools/slice_boards.py
"""
import json
import os

from PIL import Image, ImageDraw

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SPEC = os.path.join(ROOT, "config", "board_slices.json")
OUT = os.path.join(ROOT, "assets", "images")
CATALOG = os.path.join(ROOT, "config", "image_catalog.json")
OVERLAYS = os.path.join(ROOT, "references", "renders", "board_overlays")


def band_rects(band):
    """Yield (label, [x0,y0,x1,y1]) in preview coordinates for one band."""
    if "items" in band:
        yield from band["items"].items()
        return
    x0, y0, x1, y1 = band["rect"]
    labels = band["labels"]
    if "centers" in band:
        c = band["centers"]
        edges = [x0] + [(a + b) / 2 for a, b in zip(c, c[1:])] + [x1]
    else:
        w = (x1 - x0) / len(labels)
        edges = [x0 + i * w for i in range(len(labels) + 1)]
    for i, label in enumerate(labels):
        yield label, [edges[i], y0, edges[i + 1], y1]


def rel(path):
    return os.path.relpath(path, ROOT).replace("\\", "/")


def main():
    spec = json.load(open(SPEC))
    catalog = []
    os.makedirs(OVERLAYS, exist_ok=True)
    for key, board in spec["boards"].items():
        if "whole" in board:
            for ident, src in board["whole"].items():
                cat, name = ident.split("/")
                dst = os.path.join(OUT, cat, f"scene_{name}.png")
                os.makedirs(os.path.dirname(dst), exist_ok=True)
                Image.open(os.path.join(ROOT, src)).convert("RGB").save(dst)
                catalog.append({"id": f"{cat}/scene_{name}", "file": rel(dst), "category": cat, "board": key, "source": src})
            continue
        img = Image.open(os.path.join(ROOT, board["file"])).convert("RGB")
        s = board["scale"]
        preview = img.resize((round(img.width / s), round(img.height / s)))
        draw = ImageDraw.Draw(preview)
        for band in board["bands"]:
            cat = band["cat"]
            os.makedirs(os.path.join(OUT, cat), exist_ok=True)
            for label, r in band_rects(band):
                box = tuple(round(v * s) for v in r)
                name = f"{key.lower()}_{label}"
                dst = os.path.join(OUT, cat, name + ".png")
                crop = img.crop(box)
                crop.save(dst)
                entry = {"id": f"{cat}/{name}", "file": rel(dst), "category": cat, "board": key, "label": label,
                         "rect": list(box), "size": list(crop.size)}
                n = band.get("frames")
                if n:
                    frames = []
                    fw = crop.width / n
                    for f in range(n):
                        fdst = os.path.join(OUT, cat, f"{name}_f{f + 1:02d}.png")
                        crop.crop((round(f * fw), 0, round((f + 1) * fw), crop.height)).save(fdst)
                        frames.append(rel(fdst))
                    entry["frames"] = frames
                catalog.append(entry)
                draw.rectangle(r, outline=(0, 255, 120), width=1)
                draw.text((r[0] + 2, r[1] + 1), label[:14], fill=(0, 255, 120))
        preview.save(os.path.join(OVERLAYS, f"{key}.jpg"), quality=88)
    json.dump({"about": "Generated by tools/slice_boards.py from config/board_slices.json", "count": len(catalog),
               "images": catalog}, open(CATALOG, "w"), indent=1)
    by_cat = {}
    for e in catalog:
        by_cat[e["category"]] = by_cat.get(e["category"], 0) + 1 + len(e.get("frames", []))
    print(f"wrote {len(catalog)} images (+frames) -> assets/images: {by_cat}")


if __name__ == "__main__":
    main()
